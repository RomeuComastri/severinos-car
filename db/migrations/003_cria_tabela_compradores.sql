-- Rollback: 003_cria_tabela_compradores_rollback.sql
--
-- Dependência do módulo de vendas (Card 4): a tabela "vendas" deverá ter a coluna "comprador_id"
-- como chave estrangeira para compradores.id. Essa FK é criada pela migração de vendas, que deve
-- ser executada DEPOIS desta. Veja "Integração com o módulo de vendas" no README.

CREATE TABLE IF NOT EXISTS public.compradores (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL,
    cpf         VARCHAR(11) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    telefone    VARCHAR(20) NOT NULL,
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

ALTER TABLE public.compradores
    ADD COLUMN IF NOT EXISTS telefone VARCHAR(20) NOT NULL DEFAULT '';

ALTER TABLE public.compradores
    ALTER COLUMN telefone DROP DEFAULT;

CREATE UNIQUE INDEX IF NOT EXISTS ix_compradores_cpf ON public.compradores (cpf);

ALTER TABLE public.compradores ENABLE ROW LEVEL SECURITY;

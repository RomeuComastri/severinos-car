-- Migração 004: cria a tabela de vendas (Card 4 - Registro de vendas)
-- Executar no Supabase após a migração 003 e antes de usar o módulo de vendas.

CREATE TABLE IF NOT EXISTS public.vendas (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id       INTEGER NOT NULL,
    comprador_id     INTEGER NOT NULL,
    data             DATE NOT NULL,
    valor            NUMERIC(12, 2) NOT NULL CHECK (valor > 0),
    forma_pagamento  VARCHAR(50) NOT NULL,
    criado_em        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT vendas_veiculo_id_fkey FOREIGN KEY (veiculo_id)
        REFERENCES public.veiculos(id),
    CONSTRAINT vendas_comprador_id_fkey FOREIGN KEY (comprador_id)
        REFERENCES public.compradores(id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_vendas_veiculo_id ON public.vendas (veiculo_id);
CREATE INDEX IF NOT EXISTS ix_vendas_comprador_id ON public.vendas (comprador_id);

ALTER TABLE public.vendas ENABLE ROW LEVEL SECURITY;

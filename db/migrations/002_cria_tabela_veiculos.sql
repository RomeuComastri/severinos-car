-- Rollback: 002_cria_tabela_veiculos_rollback.sql

CREATE TABLE IF NOT EXISTS public.veiculos (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa       VARCHAR(7) NOT NULL,
    marca       VARCHAR(50) NOT NULL,
    modelo      VARCHAR(50) NOT NULL,
    ano         INTEGER NOT NULL,
    cor         VARCHAR(30) NOT NULL,
    preco       NUMERIC(12, 2) NOT NULL CHECK (preco > 0),
    status      VARCHAR(10) NOT NULL DEFAULT 'disponivel' CHECK (status IN ('disponivel', 'vendido')),
    imagem_url  VARCHAR(500),
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_veiculos_placa ON public.veiculos (placa);

ALTER TABLE public.veiculos ENABLE ROW LEVEL SECURITY;
